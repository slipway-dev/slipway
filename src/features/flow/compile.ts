import {
  heredocBody,
  normalizePath,
  parentOf,
  trimLines,
} from "./vfs"
import { isComplete, nodeLabel, nodeWeight, type FlowNode, type RewardMode } from "./types"

export const DEFAULT_REWARD_PATH = "/logs/verifier/reward.txt"

/** POSIX single quotes; the only character that needs care is the quote itself. */
export function bashQuote(text: string): string {
  return `'${text.replace(/'/g, `'\\''`)}'`
}

function str(node: FlowNode, key: string): string {
  const value = node[key]
  return typeof value === "string" ? value : ""
}

/** A quoted, normalized path; the same one the simulator uses. */
function pathArg(node: FlowNode, key = "path"): string {
  return bashQuote(normalizePath(str(node, key)) ?? "/")
}

/** A heredoc delimiter that no line of `body` equals. */
function delimiterFor(body: string): string {
  const lines = new Set(body.split("\n"))
  let delimiter = "SLIPWAY_EOF"
  for (let i = 1; lines.has(delimiter); i++) delimiter = `SLIPWAY_EOF_${i}`
  return delimiter
}

function heredoc(command: string, text: string): string {
  const body = heredocBody(text)
  const delimiter = delimiterFor(body)
  return `${command} <<'${delimiter}'\n${body}${delimiter}`
}

const header = (what: string) =>
  `#!/bin/bash\n# Generated by Slipway from the ${what} in Studio. Edit them there, or replace this file.\n`

/* Checks */

const NORM = "LC_ALL=C sed -e 's/[[:space:]]*$//'"

function checkCondition(node: FlowNode): string {
  if (!isComplete("checks", node)) return "false"
  const command = bashQuote(str(node, "command"))
  const trim = node.trim !== false
  switch (node.kind) {
    case "file-exists":
      return `[ -f ${pathArg(node)} ]`
    case "dir-exists":
      return `[ -d ${pathArg(node)} ]`
    case "file-absent":
      return `[ ! -e ${pathArg(node)} ]`
    case "file-equals": {
      const p = pathArg(node)
      const expected = str(node, "expected")
      return trim
        ? `[ -f ${p} ] && [ "$(${NORM} < ${p})" = ${bashQuote(trimLines(expected))} ]`
        : `[ -f ${p} ] && printf '%s' ${bashQuote(expected)} | cmp -s - ${p}`
    }
    case "file-contains":
      return `[ -f ${pathArg(node)} ] && grep -qF -e ${bashQuote(str(node, "text"))} -- ${pathArg(node)}`
    case "command-succeeds":
      return `bash -c ${command} >/dev/null 2>&1`
    case "command-output": {
      const expected = str(node, "expected")
      return trim
        ? `[ "$(bash -c ${command} 2>/dev/null | ${NORM})" = ${bashQuote(trimLines(expected))} ]`
        : `[ "$(bash -c ${command} 2>/dev/null; printf x)" = ${bashQuote(expected + "x")} ]`
    }
    default:
      return "false"
  }
}

export interface CompileChecksOptions {
  mode?: RewardMode
  /** Where the reward goes; the container path unless a test redirects it. */
  rewardPath?: string
}

/** The verifier: tests/test.sh that runs each check and writes a reward. */
export function compileChecks(nodes: FlowNode[], options: CompileChecksOptions = {}): string {
  const mode = options.mode ?? "all"
  const rewardPath = options.rewardPath ?? DEFAULT_REWARD_PATH
  const out: string[] = [header("checks"), "earned=0", "possible=0", ""]

  nodes.forEach((node, i) => {
    const label = nodeLabel(node)
    const weight = nodeWeight(node)
    out.push(
      `# ${i + 1}. ${label}`,
      `possible=$((possible + ${weight}))`,
      `if ${checkCondition(node)}; then`,
      `  printf 'pass: %s\\n' ${bashQuote(label)}`,
      `  earned=$((earned + ${weight}))`,
      "else",
      `  printf 'fail: %s\\n' ${bashQuote(label)}`,
      "fi",
      "",
    )
  })

  if (mode === "weighted") {
    out.push(
      "# Reward: the share of weight that passed, to four decimals.",
      'if [ "$possible" -gt 0 ]; then',
      "  scaled=$((earned * 10000 / possible))",
      "  reward=$(printf '%d.%04d' $((scaled / 10000)) $((scaled % 10000)))",
      "else",
      "  reward=0",
      "fi",
    )
  } else {
    out.push(
      "# Reward: 1 only when every check passed.",
      'if [ "$possible" -gt 0 ] && [ "$earned" -eq "$possible" ]; then',
      "  reward=1",
      "else",
      "  reward=0",
      "fi",
    )
  }
  out.push(
    "",
    `mkdir -p ${bashQuote(parentOf(rewardPath))}`,
    `echo "$reward" > ${bashQuote(rewardPath)}`,
    'echo "reward: $reward"',
    "",
  )
  return out.join("\n")
}

/* Steps */

function stepCommands(node: FlowNode, index: number): string[] {
  if (!isComplete("steps", node)) {
    return [`echo ${bashQuote(`Slipway: step ${index + 1} is incomplete`)} >&2`, "exit 1"]
  }
  const p = pathArg(node)
  switch (node.kind) {
    case "write-file":
    case "append-file": {
      const dir = bashQuote(parentOf(normalizePath(str(node, "path")) ?? "/"))
      const redirect = node.kind === "write-file" ? ">" : ">>"
      return [`mkdir -p ${dir}`, heredoc(`cat ${redirect} ${p}`, str(node, "content"))]
    }
    case "make-dir":
      return [`mkdir -p ${p}`]
    case "delete":
      return [`rm -rf -- ${p}`]
    case "run-command":
      return [str(node, "command")]
    default:
      return ["false"]
  }
}

/** The solution: solution/solve.sh that carries out each step in order. */
export function compileSteps(nodes: FlowNode[]): string {
  const out: string[] = [header("steps"), "set -e", ""]
  nodes.forEach((node, i) => {
    out.push(`# ${i + 1}. ${nodeLabel(node)}`, ...stepCommands(node, i), "")
  })
  return out.join("\n")
}
