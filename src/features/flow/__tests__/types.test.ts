import { describe, expect, it } from "vitest"

import { compileChecks, compileSteps, bashQuote } from "../compile"
import { CHECK_KINDS, STEP_KINDS, createNode, describeNode, isFlowValue, nodeIssues, nodeLabel, nodeWeight } from "../types"

describe("nodes", () => {
  it("creates every kind complete except for what only the author knows", () => {
    for (const { kind } of CHECK_KINDS) {
      const node = createNode("checks", kind)
      expect(node.kind).toBe(kind)
      expect(node.id).toMatch(/^[0-9a-f]{8}$/)
    }
    expect(nodeIssues("checks", createNode("checks", "file-exists"))).toEqual([])
    expect(nodeIssues("checks", createNode("checks", "file-equals"))).toEqual([{ field: "expected", problem: "required" }])
    expect(nodeIssues("steps", createNode("steps", "make-dir"))).toEqual([])
    expect(() => createNode("checks", "nope")).toThrow(/Unknown checks kind/)
  })

  it("reports each problem with its field", () => {
    expect(nodeIssues("checks", { id: "1", kind: "file-exists", path: "relative/x" })).toEqual([
      { field: "path", problem: "not-absolute" },
    ])
    expect(nodeIssues("checks", { id: "1", kind: "file-contains", path: "/a", text: "two\nlines" })).toEqual([
      { field: "text", problem: "multiline" },
    ])
    expect(nodeIssues("steps", { id: "1", kind: "run-command", command: "  " })).toEqual([
      { field: "command", problem: "required" },
    ])
    expect(nodeIssues("steps", { id: "1", kind: "teleport" })).toEqual([{ problem: "unknown-kind" }])
    expect(nodeIssues("steps", { id: "1", kind: "write-file", path: "/app/x", content: "" })).toEqual([])
  })

  it("knows what is a flow value", () => {
    expect(isFlowValue({ nodes: [] })).toBe(true)
    expect(isFlowValue({ nodes: "x" })).toBe(false)
    expect(isFlowValue(["a"])).toBe(false)
    expect(isFlowValue(null)).toBe(false)
  })

  it("describes and labels nodes in one line", () => {
    const node = { id: "1", kind: "file-contains", path: "/app/out", text: "ok" }
    expect(describeNode(node)).toBe('file contains "ok": /app/out')
    expect(nodeLabel({ ...node, label: "  Output says ok\nok " })).toBe("Output says ok ok")
    expect(nodeLabel({ id: "2", kind: "run-command", command: "make\nmake test" })).toBe("run: make")
  })

  it("keeps weights whole and at least 1", () => {
    expect([undefined, 0, -3, 2.9, NaN, 5].map((weight) => nodeWeight({ id: "1", kind: "x", weight }))).toEqual([1, 1, 1, 2, 1, 5])
  })

  it("quotes for bash", () => {
    expect(bashQuote("it's")).toBe(`'it'\\''s'`)
    expect(bashQuote("")).toBe("''")
  })

  it("names the Slipway origin in generated scripts", () => {
    expect(compileChecks([])).toMatch(/Generated by Slipway from the checks in Studio/)
    expect(compileSteps([])).toMatch(/Generated by Slipway from the steps in Studio/)
    expect(STEP_KINDS.length + CHECK_KINDS.length).toBeGreaterThan(8)
  })
})
