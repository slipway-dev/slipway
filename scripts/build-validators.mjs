// Precompile the task.toml validator from Harbor's JSON Schema. Ajv would
// otherwise compile it at runtime with `new Function`, which Slipway's CSP
// forbids (no 'unsafe-eval'). Run after scripts/sync-harbor-schema.sh.
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import Ajv from "ajv"
import standaloneCode from "ajv/dist/standalone/index.js"

const dir = fileURLToPath(new URL("../src/features/harbor/", import.meta.url))

export function buildTaskValidator() {
  const schema = JSON.parse(readFileSync(dir + "task-schema.json", "utf8"))
  const ajv = new Ajv({ allErrors: true, strict: false, code: { source: true, esm: true } })
  const header = "// Generated by scripts/build-validators.mjs from task-schema.json. Do not edit.\n/* eslint-disable */\n"
  return header + standaloneCode(ajv, ajv.compile(schema))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(dir + "task-schema.validate.js", buildTaskValidator())
  console.log("Wrote src/features/harbor/task-schema.validate.js")
}
